"""Pre-render all spoken clips with Kokoro TTS and write src/clips.ts.

Usage: python scripts/gen_voice.py <kokoro-v1.0.onnx> <voices-v1.0.bin>
Model files: https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
"""
import io, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import soundfile as sf
from kokoro_onnx import Kokoro

VOICE, PITCH, MAX = "af_heart", 1.15, 20  # pitch up for a child-like voice
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets/voice"

ONES = "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split()
TENS = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()
def words(n):
    if n < 20: return ONES[n]
    if n < 100: return TENS[n // 10] + ("-" + ONES[n % 10] if n % 10 else "")
    return ONES[n // 100] + " hundred" + (" and " + words(n % 100) if n % 100 else "")

PHRASES = {
    "welcome": "Welcome to Tables!",
    "praise1": "Awesome!", "praise2": "Great job!", "praise3": "You got it!", "praise4": "Super star!",
    "praise5": "Amazing!", "praise6": "Well done!", "praise7": "Brilliant!", "praise8": "Woohoo!",
    "combo3": "Three in a row!", "combo5": "Five in a row! You're on fire!", "combo10": "Ten in a row! Unstoppable!",
    "levelup": "Level up!", "tryagain": "Nice try!", "done": "Great game! Look at your score!",
    "best": "Wow! A new high score!",
    "grand1": "Amazing! You are the Times Tables Champion!",
    "grand2": "Incredible! You are a Legend of Tables! You mastered every table!",
}
clips = dict(PHRASES)
for a in range(1, MAX + 1):
    clips[f"trophy{a}"] = f"Hooray! You won the trophy for the table of {words(a)}!"
    for b in range(1, MAX + 1):
        clips[f"q{a}x{b}"] = f"What is {words(a)} times {words(b)}?"
        clips[f"a{a}x{b}"] = f"{words(a)} times {words(b)} is {words(a * b)}."

k = Kokoro(sys.argv[1], sys.argv[2])
OUT.mkdir(parents=True, exist_ok=True)
FX = f"asetrate=24000*{PITCH},aresample=24000,atempo={1/PITCH:.4f},silenceremove=1:0:-45dB,areverse,silenceremove=1:0:-45dB,areverse"

def render(item):
    name, text = item
    dst = OUT / f"{name}.mp3"
    if dst.exists(): return
    audio, sr = k.create(text, voice=VOICE, speed=1.0, lang="en-us")
    buf = io.BytesIO(); sf.write(buf, audio, sr, format="WAV")
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "wav", "-i", "-", "-af", FX, "-ac", "1", "-b:a", "48k", str(dst)], input=buf.getvalue(), check=True)

with ThreadPoolExecutor(4) as pool: list(pool.map(render, clips.items()))

lines = [f"  {n}: require('../assets/voice/{n}.mp3')," for n in clips]
(ROOT / "src/clips.ts").write_text("// Generated by scripts/gen_voice.py\nexport const VOICE: Record<string, number> = {\n" + "\n".join(lines) + "\n};\n")
print(f"{len(clips)} clips")
